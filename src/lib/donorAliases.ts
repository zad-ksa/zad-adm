/**
 * هجاءاتٌ لجهةٍ مانحةٍ واحدةٍ لا تُدركها تسويةُ الاسم.
 *
 * فـ`normalizeDonorName` تُسوّي المسافاتَ والهمزاتَ والتاءَ المربوطة — وهذا
 * يكفي «بنك الجزيرة» و«بنك الجزيرة␣». ولا يكفي اسمين مختلفين لجهةٍ واحدة:
 *
 *   · «العجيمي» و«العجمي» — حرفٌ يفصل بينهما والصدرُ والعجزُ واحد.
 *   · «ريادة وأثر/ سليمان الراجحي» و«مؤسسة سليمان الراجحي الخيرية» — بوّابةٌ
 *     واحدةٌ بمسارين، دُمجتا في القاعدة في صفٍّ اسمُه يحمل الاسمين.
 *
 * **ولمَ ملفٌّ مشتركٌ لا قائمةٌ في كل سكربت؟** لأنّ القائمةَ في أحدهما دون
 * الآخر تعني أنّ الأداةَ الثانيةَ **تُنشئ الجهةَ المدموجةَ من جديد**: دفترٌ
 * يذكرها بهجاءٍ آخرَ فلا تُطابق شيئاً، فتُنشأ صفّاً ثانياً — ويعود الداءُ الذي
 * عولج بالدمج، جهةٌ واحدةٌ بسطرين وحساباتٌ مقسومةٌ بينهما. وقد وقع هذا فعلاً:
 * دفترُ رؤية للطفولة أنشأ للراجحي صفّين، وفي القاعدة صفٌّ مدموجٌ له سبعةُ
 * حسابات.
 */
import { normalizeDonorName } from "./donorOrg.ts";

export type DonorAlias = {
  /** الهجاءُ كما يُكتب في الدفاتر. */
  from: string;
  /** اسمُ الصفِّ في القاعدة. */
  to: string;
};

export const DONOR_NAME_ALIASES: readonly DonorAlias[] = [
  { from: "مؤسسة عبدالعزيز وسعد الموسى", to: "مؤسسة سعد وعبدالعزيز الموسى" },
  {
    from: "مؤسسة عبد العزيز ومحمد العجيمي وعائلتهم الخيرية",
    to: "مؤسسة عبد العزيز ومحمد العجمي وعائلتهم الخيرية",
  },
  { from: "ريادة وأثر/ سليمان الراجحي", to: "مؤسسة سليمان الراجحي الخيرية — ريادة وأثر" },
  { from: "مؤسسة سليمان الراجحي الخيرية", to: "مؤسسة سليمان الراجحي الخيرية — ريادة وأثر" },
];

/**
 * يُضيف مفاتيحَ الهجاءات إلى خريطةِ الجهات المُسوّاة.
 *
 * **ولا يُزيح صفّاً قائماً**: لو صار في القاعدة يوماً صفٌّ اسمُه هجاءٌ مذكورٌ
 * في `from` — وهو واردٌ، فـ«مؤسسة سليمان الراجحي الخيرية» اسمٌ صحيحٌ في نفسه —
 * فالمفتاحُ له لا للهجاء، وإلّا سُجِّلت حساباتُه في جهةٍ أخرى. فالهجاءُ بديلٌ
 * عند غياب الأصل لا حَكَمٌ عليه.
 *
 * ويُعيد عددَ ما أُضيف، فمن شاء قال كم هجاءً عمل.
 */
export function applyDonorAliases<T>(orgByNorm: Map<string, T>): number {
  let added = 0;
  for (const alias of DONOR_NAME_ALIASES) {
    const fromKey = normalizeDonorName(alias.from);
    if (orgByNorm.has(fromKey)) continue;
    const target = orgByNorm.get(normalizeDonorName(alias.to));
    if (!target) continue;
    orgByNorm.set(fromKey, target);
    added++;
  }
  return added;
}
