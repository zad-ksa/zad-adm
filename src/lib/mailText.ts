/**
 * نصُّ البريد المُلصَق — قسمةُ أسطرِه كما كُتبت.
 *
 * وProseMirror يقسّم النصَّ المُلصَق بـ`/(?:\r\n?|\n)+/` (في `parseFromClipboard`)،
 * والزائدةُ في آخر النمط تجمع الأسطرَ المتتاليةَ في فاصلٍ واحد: فمن ألصق نصّاً
 * بين فقراته سطورٌ فارغة وجدها كلَّها قد مُحيت وبدت الفقراتُ متلاصقة — وهو ما
 * لا يراه في شيءٍ كتبه بيده، إذ الفقرةُ الفارغةُ تبقى حين يُطبَع Enter.
 *
 * فالقسمةُ على سطرٍ واحدٍ لا على مجموعة: السطرُ الفارغ سطرٌ يُحفظ فقرةً فارغة.
 */
export function pastedTextLines(text: string): string[] {
  const lines = text.replace(/\r\n?/g, "\n").split("\n");

  // والفراغُ في آخر المُلصَق لا يقول شيئاً — ونسخُ نصٍّ يأتي معه سطرٌ أخيرٌ
  // فارغٌ في عامّة الحال. فيُحذف ما في الآخر وحدَه، ويبقى ما بين الفقرات.
  while (lines.length > 1 && lines[lines.length - 1].trim() === "") lines.pop();

  return lines;
}
