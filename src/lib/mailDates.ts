/**
 * تاريخُ الرسالة: لحظةُ إرسالها، لا لحظةُ كتابتها.
 *
 * والبريدُ بين زاد والجمعيات يوقف على التعميد، فقد يُكتب اليومَ ويُعتمد بعد
 * ثلاثة أيام. ولحظةُ الاعتماد هي لحظةُ الإرسال: فيها تُخلق صفوفُ الاستلام
 * (انظر `approveMail`)، وفيها يصل الطرفَ الآخرَ أوّلَ ما يصل. وكان يُقرأ
 * بتاريخ كتابته، فيصل الوارد اليومَ ويقع تحت بريدٍ أقدمَ منه بثلاثة أيام،
 * ويقرأ صاحبُه تاريخاً لم يَرَ فيه شيئاً.
 *
 * و`createdAt` لا يُستبدل في القاعدة: هو لحظةُ الكتابة وإرسالها إلى التعميد،
 * وموظفُ زاد يقرأ التاريخين في سجلّ الرسالة. فالتاريخان محفوظان، والمعروضُ
 * واحدٌ منهما.
 *
 * وما لا تعميدَ له — البريدُ الداخليُّ بين الموظفين — لا `approvedAt` له،
 * فيُؤرَّخ بإنشائه وهو لحظةُ إرساله. والمسودةُ تصير رسالةً في صفِّها نفسِه،
 * فيُجدَّد `createdAt` لحظةَ الإرسال (انظر `sendMail`) وإلّا قُرئت بتاريخ
 * أوّلِ حفظٍ لها. ومن كان معمِّدَ خدمته خرج بريده معتمداً باسمه، فتاريخاه
 * واحد. فالقاعدةُ واحدةٌ بلا شرطٍ ولا استثناء.
 */
export type MailDateValue = Date | string | number;

export type MailDated = {
  createdAt: MailDateValue;
  approvedAt?: MailDateValue | null;
};

/**
 * والقيمةُ تخرج بنوعها الذي دخلت به: `Date` من القاعدة ونصّاً من الحِمل
 * المُسلسَل — فلا يُضطرّ كلُّ موضعِ عرضٍ إلى تحويلٍ لا يحتاجه.
 */
export function mailSentAt<T extends MailDateValue>(mail: { createdAt: T; approvedAt?: T | null }): T {
  return mail.approvedAt ?? mail.createdAt;
}

/** ترتيبُ المحادثة: الأقدمُ إرسالاً أوّلاً — وهو ترتيبُ القراءة. */
export function byMailSentAt(a: MailDated, b: MailDated): number {
  return new Date(mailSentAt(a)).getTime() - new Date(mailSentAt(b)).getTime();
}
