/**
 * خطّةُ النشر — نصُّ فريق زادٍ للجمعية، خالصاً بلا قاعدةٍ ولا شاشة.
 *
 * وهي غيرُ المنشورات: التقويمُ مواعيدُ ومتونٌ تُعتمد منشوراً منشوراً، وهذه قولُ
 * الفريقِ في منهج النشر — على أيِّ المنصّات، وبأيِّ وتيرة، ولأيِّ غرض — يكتبه
 * زادٌ مرّةً وتقرؤه الجمعيةُ فوق تقويمها.
 *
 * **والفراغُ ليس نصّاً**: نصٌّ فارغٌ في القاعدة يُعرض لوحاً أبيضَ بلا خبر، فيُردّ
 * إلى `null` ليقول المعروضُ صراحةً «لم تُكتب بعد».
 */

export const PUBLISHING_PLAN_TITLE = "خطة النشر";

/** ما تقرؤه الجمعيةُ قبل أن يكتب زادٌ شيئاً. */
export const PUBLISHING_PLAN_EMPTY = "لم تكتب خطة النشر بعد. يكتبها فريق زاد وتظهر هنا.";

/** وما يقرؤه الكاتبُ عند زاد. */
export const PUBLISHING_PLAN_HINT = "تعرض للجمعية فوق تقويمها، وتحدث متى تغيرت.";

/**
 * حدُّ الطول: ستّةُ آلاف حرفٍ تسع صفحتين، وما زاد عليها خطّةٌ تُكتب في مستند.
 * والحدُّ هنا لا في الشاشة وحدَها: الفعلُ يقصّه كذلك، فما يُلصق من ملفٍ لا يمرّ.
 */
export const MAX_PUBLISHING_PLAN = 6000;

/**
 * تنظيفُ المكتوب: أسطرٌ موحَّدةٌ، وبلا فراغٍ في الأطراف، وبلا فجواتٍ متتابعة.
 *
 * والفراغاتُ الثلاثُ فأكثرُ تُردّ إلى سطرٍ فارغٍ واحد: نصٌّ يُلصق من مستندٍ يحمل
 * فجواتٍ تُنزل آخرَه تحت الشاشة بلا معنى.
 */
export function cleanPublishingPlan(value: string): string {
  return value
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.replace(/[ \t]+$/, ""))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()
    .slice(0, MAX_PUBLISHING_PLAN);
}

/** المكتوبُ كما يُخزَّن: نصّاً، أو `null` إن لم يبقَ فيه شيء. */
export function publishingPlanValue(value: string | null | undefined): string | null {
  if (!value) return null;
  const clean = cleanPublishingPlan(value);
  return clean.length > 0 ? clean : null;
}
