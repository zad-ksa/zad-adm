async function state() {
  const versions = await pool.query(`SELECT count(*)::int AS c FROM "ProjectBuilderPromptVersion"`);
  const options = await pool.query(`SELECT 1 FROM "GlobalSetting" WHERE key = 'PROJECT_BUILDER_OPTIONS'`);
  return { versionCount: versions.rows[0].c, hasOptions: options.rowCount > 0 };
}

(async () => {
  const before = await state();
  console.log("قبل:");
  console.log("  إصدارات البرومبت المحفوظة: " + before.versionCount);
  console.log("  قيود/محاور محفوظة مسبقاً: " + (before.hasOptions ? "نعم" : "لا"));

  if (!APPLY) {
    console.log("\nمعاينة فقط. سيُنفَّذ:");
    if (before.versionCount === 0) console.log("  • إضافة أول إصدار للبرومبت المعتمد");
    else console.log("  • تخطّي البرومبت — يوجد إصدار محفوظ أصلاً");
    if (!before.hasOptions) console.log("  • إضافة قيود المحتوى ومحاور الوثيقة المعيارية الافتراضية");
    else console.log("  • تخطّي القيود والمحاور — محفوظة أصلاً");
    console.log("\nللتنفيذ: node scripts/seed-project-builder-data.js --apply");
    await pool.end();
    return;
  }

  if (before.versionCount === 0) {
    await pool.query(
      `INSERT INTO "ProjectBuilderPromptVersion" (id, template, "createdByName", note)
       VALUES ($1, $2, $3, $4)`,
      [randomUUID(), PROMPT, "زرع أولي", "البرومبت المعتمد"]
    );
    console.log("✓ أُضيف أول إصدار للبرومبت المعتمد");
  } else {
    console.log("— تخطّي البرومبت: يوجد إصدار محفوظ أصلاً");
  }

  if (!before.hasOptions) {
    await pool.query(
      `INSERT INTO "GlobalSetting" (id, key, value, "updatedAt") VALUES ($1, 'PROJECT_BUILDER_OPTIONS', $2, CURRENT_TIMESTAMP)`,
      [randomUUID(), JSON.stringify({ exclusions: EXCLUSIONS, sections: SECTIONS })]
    );
    console.log("✓ أُضيفت قيود المحتوى ومحاور الوثيقة المعيارية الافتراضية");
  } else {
    console.log("— تخطّي القيود والمحاور: محفوظة أصلاً");
  }

  const after = await state();
  console.log("\nبعد:");
  console.log("  إصدارات البرومبت المحفوظة: " + after.versionCount);
  console.log("  قيود/محاور محفوظة: " + (after.hasOptions ? "نعم" : "لا"));

  await pool.end();
})().catch(async (e) => {
  console.error("فشل:", e.message);
  await pool.end();
  process.exit(1);
});
